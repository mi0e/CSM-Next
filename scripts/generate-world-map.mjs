/**
 * Pre-projects the komari-next dashboard world map (NodeMapView) so the theme
 * ships plain SVG path strings and needs no d3/topojson at runtime.
 *
 * Input:  vendor/world-atlas/countries-50m.json (world-atlas 50m TopoJSON, the
 *         same file komari-next bundles as src/data/world-countries-50m.json)
 * Output: src/assets/data/world-map.js (committed; lazy-loaded by the dashboard)
 *
 * Regenerate (d3-geo / topojson-client are throwaway, never committed deps):
 *
 *   mkdir "$TMP/csm-map-deps" && cd "$TMP/csm-map-deps" && echo {} > package.json
 *   npm i --no-save d3-geo@3 topojson-client@3
 *   cd - && node scripts/generate-world-map.mjs "$TMP/csm-map-deps"
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const depsDir = process.argv[2]
if (!depsDir) {
  console.error('usage: node scripts/generate-world-map.mjs <dir containing node_modules/d3-geo and topojson-client>')
  process.exit(1)
}
const requireFrom = createRequire(join(resolve(depsDir), 'package.json'))
const load = name => import(pathToFileURL(requireFrom.resolve(name)).href)
const { geoGraticule10, geoNaturalEarth1, geoPath } = await load('d3-geo')
const { feature } = await load('topojson-client')

// komari-next NodeMapView.tsx constants, kept identical.
const SVG_WIDTH = 1000
const SVG_HEIGHT = 560
const MAP_HORIZONTAL_PADDING = 28
const MAP_TOP_PADDING = 42
const MAP_BOTTOM_INSET = 42
const SMALL_REGION_MARKER_AREA_THRESHOLD = 14
const SMALL_REGION_MARKER_SIZE_THRESHOLD = 7

const topology = JSON.parse(await readFile(join(root, 'vendor/world-atlas/countries-50m.json'), 'utf8'))
const countriesGeo = feature(topology, topology.objects.countries)
const projection = geoNaturalEarth1().fitExtent(
  [[MAP_HORIZONTAL_PADDING, MAP_TOP_PADDING], [SVG_WIDTH - MAP_HORIZONTAL_PADDING, SVG_HEIGHT - MAP_BOTTOM_INSET]],
  countriesGeo
)
// Measurements use full precision (as komari does); only emitted strings are rounded.
const measure = geoPath(projection)
const draw = geoPath(projection).digits(1)
const round = value => Math.round(value * 10) / 10
const num = tenths => (tenths / 10).toString().replace(/^(-?)0\./, '$1.')

// d3 emits absolute "M x,y L x,y ... Z"; rewrite as relative moves in whole tenths
// (exact, no float drift) and drop segments that round to zero length.
function compact(path) {
  let out = ''
  let x = 0
  let y = 0
  let startX = 0
  let startY = 0
  let last = ''
  const emit = (command, dx, dy) => {
    const head = command === last ? '' : command
    const a = num(dx)
    const b = num(dy)
    out += `${head || (a.startsWith('-') ? '' : ' ')}${a}${b.startsWith('-') ? '' : ' '}${b}`
    last = command
  }
  for (const [, command, args] of path.matchAll(/([MLZ])([^MLZ]*)/g)) {
    if (command === 'Z') {
      out += 'z'
      last = 'z'
      x = startX
      y = startY
      continue
    }
    const [px, py] = args.split(',').map(value => Math.round(Number(value) * 10))
    if (command === 'M') {
      emit('m', px - x, py - y)
      startX = px
      startY = py
    } else if (px !== x || py !== y) {
      emit('l', px - x, py - y)
    }
    x = px
    y = py
  }
  return out
}

const countries = []
for (const country of countriesGeo.features) {
  const name = country.properties?.name ?? String(country.id ?? 'unknown')
  const d = compact(draw(country) ?? '')
  if (!d) continue
  const [[x0, y0], [x1, y1]] = measure.bounds(country)
  const [mx, my] = measure.centroid(country)
  const small = measure.area(country) < SMALL_REGION_MARKER_AREA_THRESHOLD ||
    Math.max(x1 - x0, y1 - y0) < SMALL_REGION_MARKER_SIZE_THRESHOLD
  // [name, path, markerX?, markerY?]: a marker point exists only for regions too small to see.
  countries.push(small && Number.isFinite(mx) && Number.isFinite(my) ? [name, d, round(mx), round(my)] : [name, d])
}

const data = {
  width: SVG_WIDTH,
  height: SVG_HEIGHT,
  sphere: compact(draw({ type: 'Sphere' })),
  graticule: compact(draw(geoGraticule10())),
  countries
}
const output = join(root, 'src/assets/data/world-map.js')
await mkdir(dirname(output), { recursive: true })
await writeFile(output, `// Generated by scripts/generate-world-map.mjs from world-atlas 50m (Natural Earth, public domain). Do not edit.\nexport default ${JSON.stringify(data)}\n`)
console.log(`Wrote ${output}: ${countries.length} countries, ${countries.filter(item => item.length > 2).length} marker candidates`)
